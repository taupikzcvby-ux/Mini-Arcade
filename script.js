function openGame(game) {

    if (game === "dino") {
        window.location.href = "games/dino/index.html";
    }

    else if (game === "snake") {
        window.location.href = "games/snake/index.html";
    }

    else if (game === "tictactoe") {
        window.location.href = "games/tictactoe/index.html";
    }

    else if (game === "fighting") {
        window.location.href = "games/fighting/index.html";
    }

    else if (game === "shooter") {
        window.location.href = "games/shooter/index.html";
    }

    else if (game === "memory") {
        window.location.href = "games/memory/index.html";
    }

}
